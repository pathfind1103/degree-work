def get_params():
    """Возвращает значения параметров по умолчанию для заполнения формы ввода."""
    return {
        "v0": "100.0",
        "angle": "45.0",
        "m": "1.0",
        "S": "0.01",
        "rho0": "1.225",
        "H0": "8430.0",
        "Cx": "0.3",
        "Cy": "0.05",   # небольшое значение для демонстрации эффекта подъёмной силы
        "g": "9.81"
    }


def calculate(params):
    """
    Выполняет пошаговое численное интегрирование системы уравнений (77)
    методом Рунге-Кутты 4-го порядка.

    Args:
        params (dict): Входные данные из полей интерфейса.

    Returns:
        tuple: (x_coords, y_coords, label)
    """
    # Преобразование параметров
    v0 = float(params.get('v0', 100.0))
    alpha = np.radians(float(params.get('angle', 45.0)))
    m = float(params.get('m', 1.0))
    S = float(params.get('S', 0.01))
    rho0 = float(params.get('rho0', 1.225))
    H0 = float(params.get('H0', 8430.0))
    Cx = float(params.get('Cx', 0.3))
    Cy = float(params.get('Cy', 0.05))
    g = float(params.get('g', 9.81))

    # Начальный вектор состояния u = [x, y, vx, vy]
    state = np.array([0.0, 0.0, v0 * np.cos(alpha), v0 * np.sin(alpha)])

    dt = 0.005                    # Шаг интегрирования
    trajectory = [state.copy()]

    def get_derivatives(s):
        """Вычисляет правую часть системы ОДУ (77)."""
        _, y_curr, vx_curr, vy_curr = s
        v = np.sqrt(vx_curr**2 + vy_curr**2)

        if v < 1e-9:
            return np.array([vx_curr, vy_curr, 0.0, -g])

        rho = rho0 * np.exp(-y_curr / H0)

        # Точно по уравнению (77)
        ax = - (rho * Cx * S * v * vx_curr) / (2 * m)
        ay = (-g
              - (rho * Cx * S * v * vy_curr) / (2 * m)
              + (rho * Cy * S * v**2) / (2 * m))

        return np.array([vx_curr, vy_curr, ax, ay])

    # Основной цикл RK4
    max_steps = 40000
    for _ in range(max_steps):
        curr_s = trajectory[-1]

        k1 = get_derivatives(curr_s)
        k2 = get_derivatives(curr_s + k1 * dt / 2)
        k3 = get_derivatives(curr_s + k2 * dt / 2)
        k4 = get_derivatives(curr_s + k3 * dt)

        new_state = curr_s + (dt / 6.0) * (k1 + 2*k2 + 2*k3 + k4)

        if new_state[1] < 0:
            # Линейная интерполяция точки падения
            prev_y = curr_s[1]
            last_y = new_state[1]
            fraction = prev_y / (prev_y - last_y)
            x_impact = curr_s[0] + fraction * (new_state[0] - curr_s[0])
            trajectory.append(np.array([x_impact, 0.0, 0.0, 0.0]))
            break

        trajectory.append(new_state)

    data = np.array(trajectory)
    return data[:, 0], data[:, 1], "Траектория в атмосфере"


# Для быстрой проверки модуля
if __name__ == "__main__":
    params = get_params()
    x, y, label = calculate(params)
    print(f"Расчёт завершён. Дальность: {x[-1]:.1f} м | Макс. высота: {y.max():.1f} м")
