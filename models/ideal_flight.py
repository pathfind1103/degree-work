"""
Модуль расчета идеальной траектории полета.
Описывает движение материальной точки в безвоздушном пространстве
под действием только силы тяжести.
"""

import numpy as np


def get_name():
    """Возвращает название модели для отображения в списке."""
    return "1. Идеальный полет (вакуум)"


def get_info():
    """
    Возвращает метаданные модели: описание, формулу в формате LaTeX
    и расшифровку используемых переменных.
    """
    return {
        "description": (
            "Классическая модель движения тела в однородном поле тяжести. "
            "Сопротивление среды не учитывается. Траектория представляет собой "
            "симметричную параболу, а дальность полета максимальна при угле 45°."
        ),
        "formula": r"$y = x \cdot \mathrm{tg}(\alpha) - \frac{g \cdot x^2}{2 v_0^2 \cos^2(\alpha)}$",
        "parameters_info": {
            "v0": "Начальная скорость вылета тела (м/с)",
            "angle": "Угол броска к горизонту (градусы)",
            "g": "Ускорение свободного падения (м/с²)"
        }
    }


def get_params():
    """Возвращает параметры по умолчанию для инициализации полей ввода."""
    return {
        "v0": "50.0",
        "angle": "45.0",
        "g": "9.81"
    }


def calculate(params):
    """
    Выполняет аналитический расчет координат траектории.

    Args:
        params (dict): Словарь параметров (v0, angle, g).

    Returns:
        tuple: (x_coords, y_coords, label)
    """
    # Приведение типов данных
    v0 = float(params.get('v0', 50))
    alpha_deg = float(params.get('angle', 45))
    g = float(params.get('g', 9.81))

    alpha = np.radians(alpha_deg)

    # Расчет времени полета до касания земли (y=0)
    t_max = (2 * v0 * np.sin(alpha)) / g

    # Генерация временной сетки (100 точек для плавности графика)
    t = np.linspace(0, t_max, 100)

    # Кинематические уравнения движения
    x = v0 * t * np.cos(alpha)
    y = v0 * t * np.sin(alpha) - 0.5 * g * t ** 2

    return x, y, "Идеальная парабола"
