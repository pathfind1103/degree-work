"""
Модуль статистического моделирования методом Монте-Карло.

Описывает ансамбль баллистических траекторий обтекаемого тела.
В расчетах учитывается стохастический характер внешней среды и начальных условий:
1. Случайные пульсации ветра (скорость ветра распределена по Гауссу).
2. Погрешность начальной скорости вылета (нормальное распределение).
3. Квадратичное сопротивление воздуха и подъемная сила.

Интегрирование каждой реализации выполняется методом Рунге-Кутты 4-го порядка (RK4).
"""

