"""
Модуль численного моделирования траектории обтекаемого тела в атмосфере.

Данный модуль реализует расчет движения материальной точки с учетом:
1. Постоянного поля тяжести (ускорение g).
2. Квадратичного закона аэродинамического сопротивления (сила Cx).
3. Аэродинамической подъемной силы (сила Cy), возникающей за счет формы тела.
4. Экспоненциальной модели изменения плотности атмосферы в зависимости от высоты.

Математический аппарат:
Решение системы нелинейных обыкновенных дифференциальных уравнений (ОДУ)
выполняется классическим численным методом Рунге-Кутты 4-го порядка (RK4),
что обеспечивает высокую точность и стабильность без использования сторонних солверов.
"""

